def _fill(text, values):
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", v)
    return text


def render(book):
    s = book.sources
    if s:
        p = s.prefix
        src = {"name": s.name, "p": p, "first_id": s.repos[0].id,
               "repo_list": ", ".join(f"{r.id} = {r.label} ({r.root})" for r in s.repos),
               "version_values": " 또는 ".join(f'"{r.id}"' for r in s.repos),
               "path_example": s.path_example.split(",")[0].strip()}
        source_rules = s.rules.strip("\n") or _fill(SOURCE_RULES_DEFAULT, src)
        evidence = s.edit_rules.strip("\n") or _fill(EVIDENCE_WITH_SOURCES, src)
        values = {"check_with": f"책과 로컬 {s.name} 소스(아래)로", "answer_with": "책이나 로컬 소스로",
                  "image_rule": f"이미지가 책이나 {s.name}와 관련되면 책 절·소스와 연결해 설명하고,\n"
                                "  이미지에서 읽은 것과 책·소스로 확인한 것을 구분합니다.",
                  "source_note": f"{s.name} 소스는 book MCP 서버의 {p}_search·{p}_read 도구로만 찾고 읽습니다.\n"}
    else:
        source_rules, evidence = "", EVIDENCE_BOOK_ONLY
        values = {"check_with": "책으로", "answer_with": "책으로",
                  "image_rule": "이미지가 책과 관련되면 책 절과 연결해 설명하고,\n"
                                "  이미지에서 읽은 것과 책으로 확인한 것을 구분합니다.",
                  "source_note": ""}
    values.update(topics=book.topics, cite_example=book.cite_example, style=book.style, evidence_rules=evidence)
    return {"STYLE": STYLE, "RULES": _fill(RULES, values), "SOURCE_RULES": source_rules,
            "EDIT_RULES": _fill(EDIT_RULES, values), "CODEX_NOTE": _fill(CODEX_NOTE, values)}
